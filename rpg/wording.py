# 这些只在网页源码里换，后端消息不用（后端用主题名词表 T()）
_cache = {}


def sl(text, web=False):
    for a, b in (WEB_EXTRA + MAP if web else MAP):
        if a in text:
            text = text.replace(a, b)
    return text


def web(path, raw, subject):
    """静态文件：申论科目下换措辞（.js / .html），其余原样返回。raw 是 bytes"""
    if subject != "申论" or "vendor/" in str(path).replace("\\", "/") or not str(path).endswith((".js", ".html")):
        return raw
    key = (str(path), subject, hash(raw))
    if key not in _cache:
        _cache[key] = sl(raw.decode("utf-8"), web=True).encode("utf-8")
    return _cache[key]


def fix_events(obj):
    """申论科目：接口返回里程序自己写的提示事件（{"kind": "info"|"xp"…, "msg": …}）换成官场措辞。
    只动带 kind 的事件字典，不动用户内容（笔记、作答、AI 的话、记录里的 note）。原地修改并返回 obj。"""
    if isinstance(obj, dict):
        if obj.get("kind") in ("info", "xp", "warn") and isinstance(obj.get("msg"), str):
            obj["msg"] = sl(obj["msg"])
        for v in obj.values():
            if isinstance(v, (dict, list)):
                fix_events(v)
    elif isinstance(obj, list):
        for v in obj:
            if isinstance(v, (dict, list)):
                fix_events(v)
    return obj


def fix_system(messages):
    """申论科目：发给 AI 的 system 提示里的修仙说法换成官场说法（user / assistant 消息是用户和 AI 的原话，不动）"""
    out = []
    for m in messages:
        if m.get("role") == "system" and isinstance(m.get("content"), str):
            m = dict(m, content=sl(m["content"]))
        out.append(m)
    return out
